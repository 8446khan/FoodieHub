# ==========================================
# BULK INSERT INTO DATABASE
# ==========================================

with app.app_context():
    inserted_count = 0
    skipped_count = 0

    print("\n--- FoodieHub Product Seeder ---")

    try:
        for item in sample_products:
            existing_product = Product.query.filter(
                func.lower(Product.name) == item["name"].lower()
            ).first()

            if existing_product:
                print(f"Skipped existing product: {item['name']}")
                skipped_count += 1
                continue

            product = Product(**item)

            db.session.add(product)
            inserted_count += 1

        db.session.commit()

        print("\nBulk insertion completed successfully!")
        print(f"Products inserted: {inserted_count}")
        print(f"Products skipped: {skipped_count}")
        print(f"Total products in seed list: {len(sample_products)}")

    except Exception as error:
        db.session.rollback()
        print("\nBulk insertion failed.")
        print("Error:", error)
